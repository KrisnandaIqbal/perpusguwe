(function () {
  // Satu lembar kertas = bentuk SVG yang lengkungannya dihitung ulang tiap frame.
  // Halaman diam kiri/kanan digambar dengan fungsi yang sama, jadi lembar mendarat tanpa sambungan.
  function leafAt(e) {
    var L = 148.75, N = 40, ds = L / N, cy = 94, P = 2400;
    var y0 = 1.25, H = 185.5, r = 10, lag = 0.28;

    // Tiap baris punya fase sendiri: sudut atas naik duluan, tepi bawah menyusul.
    function row(v) {
      var u = Math.max(0, Math.min(1, (e - lag * v) / (1 - lag)));
      u = u * u * (3 - 2 * u);
      var bend = 1.5 * Math.sin(2 * Math.PI * u);
      var th = Math.PI * u - bend / 2;
      var xs = [0], zs = [0], sh = 0;
      for (var i = 0; i < N; i++) {
        var phi = Math.min(Math.PI, Math.max(0, th + bend * (i + 0.5) / N));
        xs.push(xs[i] + Math.cos(phi) * ds);
        zs.push(zs[i] + Math.sin(phi) * ds);
        sh += Math.sin(phi) / N;
      }
      return { xs: xs, zs: zs, sh: sh, y: y0 + v * H };
    }
    function pt(x, z, y) {
      var sc = P / (P - z);
      return (150 + x * sc).toFixed(2) + ' ' + (cy + (y - cy) * sc).toFixed(2);
    }
    function at(c, s) {
      var k = Math.min(N - 1, Math.floor(s / ds));
      var f = (s - k * ds) / ds;
      return pt(c.xs[k] + (c.xs[k + 1] - c.xs[k]) * f, c.zs[k] + (c.zs[k + 1] - c.zs[k]) * f, c.y);
    }
    function tip(c) { return pt(c.xs[N], c.zs[N], c.y); }

    var cTop = row(0), cBot = row(1), top = [], bottom = [];
    for (var i = 0; i <= N; i++) {
      if (i * ds < L - r) {
        top.push(pt(cTop.xs[i], cTop.zs[i], cTop.y));
        bottom.unshift(pt(cBot.xs[i], cBot.zs[i], cBot.y));
      }
    }
    top.push(at(cTop, L - r));
    bottom.unshift(at(cBot, L - r));
    var edge = [r / H, 0.2, 0.35, 0.5, 0.65, 0.8, 1 - r / H].map(function (v) { return tip(row(v)); });
    var o = 'M' + top.join(' L') +
      ' Q' + tip(cTop) + ' ' + edge.join(' L') +
      ' Q' + tip(cBot) + ' ' + bottom.join(' L') + ' Z';

    var l = '';
    [27.5, 41.5, 55.5, 69.5].forEach(function (y) {
      var c = row((y - y0) / H);
      var pts = [at(c, 14)];
      for (var i = 1; i < N; i++) {
        var s = i * ds;
        if (s > 14 && s < L - 14) pts.push(pt(c.xs[i], c.zs[i], c.y));
      }
      pts.push(at(c, L - 14));
      l += 'M' + pts.join(' L') + ' ';
    });
    var shade = (cTop.sh + cBot.sh + row(0.5).sh) / 3;
    return { o: o, l: l, f: 'hsl(220, 16%, ' + (100 - 10 * shade).toFixed(1) + '%)' };
  }

  function draw(id, g) {
    document.getElementById(id + '-o').setAttribute('d', g.o);
    document.getElementById(id + '-l').setAttribute('d', g.l);
    if (id === 'leaf') document.getElementById('leaf-o').setAttribute('fill', g.f);
  }

  draw('right', leafAt(0));
  draw('left', leafAt(1));
  draw('leaf', leafAt(0));

  var still = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (!still) {
    var start = performance.now();
    (function frame(now) {
      var ph = (((now - start) / 1000) % 2.6) / 2.6;
      var e = 0;
      if (ph >= 0.82) e = 1;
      else if (ph > 0.12) e = 0.5 - 0.5 * Math.cos(Math.PI * (ph - 0.12) / 0.7);
      draw('leaf', leafAt(e));
      requestAnimationFrame(frame);
    })(start);
  }

  var phrases = ['menata ulang rak buku', 'merapikan katalog', 'menyiapkan layanan'];
  var typed = document.getElementById('typed');
  var n = 0, p = 0, del = false, pause = 0;
  setInterval(function () {
    var word = phrases[n];
    if (!del && p < word.length) p++;
    else if (!del) { if (++pause < 20) return; pause = 0; del = true; }
    else if (p > 0) p--;
    else { del = false; n = (n + 1) % phrases.length; }
    typed.textContent = word.slice(0, p);
  }, 75);
})();
